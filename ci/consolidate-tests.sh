#!/bin/sh
# ci/consolidate-tests.sh [--check] -- one integration-test program per crate (docs/CI.md, "One
# test program per crate").
#
# Cargo makes every tests/<name>.rs its own test program, linked against the crate and all its
# dependencies. For every workspace crate with more than one such file this script folds them
# into one program, `it`:
#
# - tests/main.rs (generated here; re-run the script rather than editing it) declares the shared
#   support directories (tests/<dir>/mod.rs) once and every tests/<name>.rs as the module <name>,
#   so a test is called `<name>::<test>` (`cargo test -p <package> --test it <name>::`);
# - in each folded file a line `mod <dir>;` naming a support directory becomes `use crate::<dir>;`;
# - the crate's Cargo.toml gets `autotests = false` and `[[test]] name = "it"`, plus a `[[test]]`
#   for each file that stays its own program.
#
# The files keep their paths, so the goldens, fixtures and paths in comments stay as they are, and
# ci/test-tiers.txt keeps naming them `<package>::<name>` (ci/tier-filter.sh turns such a line into
# a filter on the `it` program's test names). Files that stay their own program: those a
# `[[test]]` of the crate's Cargo.toml already names (for example hydo-explore's fake_engine,
# `harness = false` with its own main), and the files listed in SEPARATE below, each with why.
#
# It is idempotent: run it after adding a tests/<name>.rs (or after merging a branch that adds
# one), then `cargo fmt`. hydo-release's test_tiers test fails while a tests/*.rs of a workspace
# crate is in no test program. With --check it changes nothing and exits 1 when it would.
set -eu
check=false
if [ "${1:-}" = --check ]; then
  check=true
fi
root=$(git rev-parse --show-toplevel)
cd "$root"

# <file> <reason>: integration-test files that stay their own test program
SEPARATE='
hydo/crates/hydo-grpc-gen/tests/client.rs sets HYDO_SEED, HYDO_OUTCOMES, HYDO_ACKED and HYDO_GRPC_CONSOLE in the process environment (under its own lock); the other tests of the crate would see them under cargo test, which runs one program'"'"'s tests as threads of one process
'

changed=false
note() {
  echo "consolidate-tests: $*"
  changed=true
}

members=$(sed -n 's/^[[:space:]]*"\(hydo\/crates\/[^"]*\)",*$/\1/p' Cargo.toml)
for d in $members; do
  t=$d/tests
  [ -d "$t" ] || continue
  # the tests/*.rs a [[test]] of Cargo.toml names (other than the one this script makes)
  explicit=$(awk '
    /^\[\[test\]\]/ { intest = 1; next }
    /^\[/ { intest = 0 }
    intest && /^path[[:space:]]*=/ { p = $0; sub(/^[^"]*"/, "", p); sub(/".*/, "", p); print p }
  ' "$d/Cargo.toml" | grep -v '^tests/main\.rs$' || true)
  fold=""
  separate=""
  for f in "$t"/*.rs; do
    [ -e "$f" ] || continue
    b=${f#"$d/"}
    [ "$b" = tests/main.rs ] && continue
    if printf '%s\n' $explicit | grep -qx "$b"; then
      continue
    fi
    if printf '%s\n' "$SEPARATE" | grep -q "^$f "; then
      separate="$separate $b"
      continue
    fi
    fold="$fold $(basename "$f" .rs)"
  done
  n=$(printf '%s\n' $fold | grep -c . || true)
  if [ ! -f "$t/main.rs" ] && [ "$n" -lt 2 ]; then
    continue
  fi
  pkg=$(sed -n 's/^name[[:space:]]*=[[:space:]]*"\(.*\)"/\1/p' "$d/Cargo.toml" | head -n 1)

  # the support directories (tests/<dir>/mod.rs)
  support=""
  for m in "$t"/*/mod.rs; do
    [ -e "$m" ] || continue
    support="$support $(basename "$(dirname "$m")")"
  done
  # each folded file: `mod <dir>;` -> `use crate::<dir>;`
  used=""
  for name in $fold; do
    f=$t/$name.rs
    for s in $support; do
      if grep -qx "mod $s;" "$f"; then
        if $check; then
          note "$f: would turn \`mod $s;\` into \`use crate::$s;\`"
        else
          perl -pi -e "s/^mod \Q$s\E;\$/use crate::$s;/" "$f"
          note "$f: \`mod $s;\` -> \`use crate::$s;\`"
        fi
      fi
      if grep -q -e "^mod $s;\$" -e "use crate::$s;" -e "crate::$s::" "$f"; then
        case " $used " in *" $s "*) ;; *) used="$used $s" ;; esac
      fi
    done
    other=$(awk -v support=" $support " '
      /^[[:space:]]*mod [a-z_0-9]*;/ {
        m = $0; sub(/^[[:space:]]*mod /, "", m); sub(/;.*/, "", m)
        if (!($0 ~ /^mod / && index(support, " " m " ") > 0)) print FILENAME ":" NR ": " $0
      }' "$f")
    if [ -n "$other" ]; then
      echo "consolidate-tests: $f declares a module that is not a support directory of $t:" >&2
      echo "$other" >&2
      exit 1
    fi
  done

  # tests/main.rs
  new=$(mktemp)
  {
    echo "//! The integration tests of $pkg as one test program (generated by"
    echo "//! ci/consolidate-tests.sh, which docs/CI.md \"One test program per crate\" explains: re-run it"
    echo "//! after adding a tests/<name>.rs). Each tests/<name>.rs is the module <name>, so its tests are"
    echo "//! \`<name>::<test>\`: \`cargo test -p $pkg --test it <name>::\`."
    if [ -n "$used" ]; then
      echo
      for s in $(printf '%s\n' $used | LC_ALL=C sort); do echo "mod $s;"; done
    fi
    echo
    for name in $(printf '%s\n' $fold | LC_ALL=C sort); do echo "mod $name;"; done
  } > "$new"
  if ! cmp -s "$new" "$t/main.rs" 2>/dev/null; then
    if $check; then
      note "$t/main.rs: would be written"
      rm -f "$new"
    else
      mv "$new" "$t/main.rs"
      note "$t/main.rs written ($n modules)"
    fi
  else
    rm -f "$new"
  fi

  # Cargo.toml
  c=$d/Cargo.toml
  if ! grep -q '^autotests[[:space:]]*=[[:space:]]*false' "$c"; then
    if $check; then
      note "$c: would get autotests = false"
    else
      # after the [package] table's name line
      perl -0pi -e 's/(\[package\]\n(?:[^\[\n][^\n]*\n|\n)*?name\s*=\s*"[^"]*"\n)/$1# every tests\/<name>.rs is a module of the one test program `it` (tests\/main.rs,\n# ci\/consolidate-tests.sh)\nautotests = false\n/' "$c"
      grep -q '^autotests = false' "$c" || {
        echo "consolidate-tests: could not add autotests = false to $c" >&2
        exit 1
      }
      note "$c: autotests = false"
    fi
  fi
  if ! grep -q '^path = "tests/main.rs"' "$c"; then
    if $check; then
      note "$c: would get [[test]] it"
    else
      printf '\n# the integration tests, one program (ci/consolidate-tests.sh)\n[[test]]\nname = "it"\npath = "tests/main.rs"\n' >> "$c"
      note "$c: [[test]] it"
    fi
  fi
  for b in $separate; do
    if ! grep -q "^path = \"$b\"" "$c"; then
      name=$(basename "$b" .rs)
      why=$(printf '%s\n' "$SEPARATE" | sed -n "s|^$d/$b ||p")
      if $check; then
        note "$c: would get [[test]] $name"
      else
        {
          printf "\n"
          printf "its own test program (ci/consolidate-tests.sh): it %s\n" "$why" | fold -s -w 96 | sed "s/^/# /; s/ *\$//"
          printf '[[test]]\nname = "%s"\npath = "%s"\n' "$name" "$b"
        } >> "$c"
        note "$c: [[test]] $name (its own program)"
      fi
    fi
  done
done

if $check && $changed; then
  echo "consolidate-tests: run ci/consolidate-tests.sh, then cargo fmt" >&2
  exit 1
fi
exit 0
